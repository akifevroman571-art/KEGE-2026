with open('files/26_17643.txt') as f:
    N = int(f.readline())
    goods = [list(map(int, i.split())) for i in f]

middle = sum(i[1] for i in goods) / N
products = {}
for ID, price, st in goods:
    if price > middle:
        if ID not in products:
            products[ID] = [not st, price, st]
        else:
            products[ID][2] += st
            products[ID][0] += (not st)

products2 = sorted(products, key=lambda x: (products[x][0], products[x][1], -products[x][2]))
print(products[products2[-1]][1]*products[products2[-1]][0], products[products2[-1]][-1])






























































































































































































































































































































































